CREATE TABLE CLB
(
	IDCLB char(10),
	TenCLB nvarchar(50),
	DiaChi nvarchar(50)
	PRIMARY KEY (IDCLB)
)
GO
CREATE TABLE DOI
(
	IDCLB char(10),
	IDDoi char(10),
	TenDoi nvarchar(30),
	IDDoiTruong char(10)
	PRIMARY KEY (IDCLB, IDDoi)
)
GO
