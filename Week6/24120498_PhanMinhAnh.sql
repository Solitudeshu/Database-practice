-- Q58
SELECT G.HOTEN
FROM GIAOVIEN G 
JOIN THAMGIADT T ON G.MAGV = T.MAGV
JOIN DETAI D ON D.MADT = T.MADT
GROUP BY G.MAGV, G.HOTEN
HAVING COUNT(DISTINCT D.MACD) = (
	SELECT COUNT(*)
	FROM CHUDE
)

