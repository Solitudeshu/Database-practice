-- Q51
SELECT K.TENKHOA
FROM KHOA K
JOIN BOMON B ON K.MAKHOA = B.MAKHOA
JOIN GIAOVIEN G ON B.MABM = G.MABM
GROUP BY K.MAKHOA, K.TENKHOA
HAVING COUNT(G.MAGV) >= ALL (
    SELECT COUNT(G2.MAGV)
    FROM KHOA K2
    JOIN BOMON B2 ON K2.MAKHOA = B2.MAKHOA
    JOIN GIAOVIEN G2 ON B2.MABM = G2.MABM
    GROUP BY K2.MAKHOA
)

-- Q52
SELECT G.HOTEN
FROM GIAOVIEN G
JOIN DETAI D ON G.MAGV = D.GVCNDT
GROUP BY G.MAGV, G.HOTEN
HAVING COUNT(D.MADT) >= ALL (
    SELECT COUNT(D2.MADT)
    FROM GIAOVIEN G2
    JOIN DETAI D2 ON G2.MAGV = D2.GVCNDT
    GROUP BY G2.MAGV
)

