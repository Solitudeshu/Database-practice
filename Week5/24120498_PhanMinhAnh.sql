WHERE G.MABM = 'HTTT'
GROUP BY G.MAGV, G.HOTEN
HAVING COUNT(DISTINCT T.MADT) >= ALL (
    SELECT COUNT(DISTINCT T2.MADT)
    FROM GIAOVIEN G2
    JOIN THAMGIADT T2 ON G2.MAGV = T2.MAGV
    WHERE G2.MABM = 'HTTT'
    GROUP BY G2.MAGV
)

-- Q56
SELECT G.HOTEN, B.TENBM
FROM GIAOVIEN G
JOIN BOMON B ON G.MABM = B.MABM
LEFT JOIN NGUOITHAN N ON G.MAGV = N.MAGV
GROUP BY G.MAGV, G.HOTEN, B.TENBM
HAVING COUNT(N.TEN) >= ALL (
    SELECT COUNT(N2.TEN)
    FROM GIAOVIEN G2
    LEFT JOIN NGUOITHAN N2 ON G2.MAGV = N2.MAGV
    GROUP BY G2.MAGV
)

-- Q57
SELECT G.HOTEN
FROM GIAOVIEN G
JOIN BOMON B ON G.MAGV = B.TRUONGBM
LEFT JOIN DETAI D ON G.MAGV = D.GVCNDT
GROUP BY G.MAGV, G.HOTEN
HAVING COUNT(D.MADT) >= ALL (
    SELECT COUNT(D2.MADT) 
    FROM BOMON B2
    LEFT JOIN DETAI D2 ON B2.TRUONGBM = D2.GVCNDT
    WHERE B2.TRUONGBM IS NOT NULL
    GROUP BY B2.TRUONGBM
)