-- Q54
SELECT G.HOTEN, B.TENBM
FROM GIAOVIEN G
JOIN BOMON B ON G.MABM = B.MABM
JOIN THAMGIADT T ON G.MAGV = T.MAGV
GROUP BY G.MAGV, G.HOTEN, B.TENBM
HAVING COUNT(DISTINCT T.MADT) >= ALL (
    SELECT COUNT(DISTINCT T2.MADT)
    FROM THAMGIADT T2
    GROUP BY T2.MAGV
)

-- Q55
