------ Câu 27 ------
SELECT COUNT(MAGV) SLGV, SUM(LUONG) TONG_LUONG
FROM GIAOVIEN

------ Câu 28 ------
SELECT B.TENBM, COUNT(G.MAGV) SLGV, AVG(LUONG) LUONG_TB 
FROM GIAOVIEN G JOIN BOMON B ON G.MABM = B.MABM
GROUP BY B.MABM, B.TENBM

------ Câu 29 ------
SELECT C.TENCD, COUNT(D.MADT) SLDT
FROM CHUDE C LEFT JOIN DETAI D ON C.MACD = D.MACD
GROUP BY C.MACD, C.TENCD

------ Câu 30 ------
SELECT HOTEN, COUNT(DISTINCT T.MADT) SLDT_TG
FROM GIAOVIEN G JOIN THAMGIADT T ON G.MAGV = T.MAGV
GROUP BY G.MAGV, HOTEN

------ Câu 31 ------
SELECT HOTEN, COUNT(D.MADT) SLDT_CN
FROM GIAOVIEN G JOIN DETAI D ON G.MAGV = D.GVCNDT
GROUP BY G.MAGV, HOTEN

------ Câu 32 ------
SELECT HOTEN, COUNT(N.MAGV) SLNT
FROM GIAOVIEN G LEFT JOIN NGUOITHAN N ON G.MAGV = N.MAGV
GROUP BY G.MAGV, HOTEN

------ Câu 33 ------
SELECT HOTEN
FROM GIAOVIEN G JOIN THAMGIADT T ON G.MAGV = T.MAGV
GROUP BY G.MAGV, HOTEN
HAVING COUNT(DISTINCT T.MADT) >= 3

------ Câu 34 ------
SELECT COUNT(DISTINCT T.MAGV) SLGV
FROM THAMGIADT T JOIN DETAI D ON T.MADT = D.MADT
WHERE D.TENDT = N'Ứng dụng hóa học xanh'